/**
 * Visual → code export (US-4.2): turn a Studio document or the current props/overrides of
 * a code template into clean TypeScript.
 */
import type { ArtisanDocument } from './schema.js';
import { serializeDocument } from './serialize.js';
import type { LayerOverrides } from '../composition/overrides.js';

const ident = (s: string) => {
  const base = s.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : '')).replace(/^[^a-zA-Z_]+/, '');
  return (base.charAt(0).toUpperCase() + base.slice(1)) || 'Design';
};

/** TypeScript module that registers a Studio document as a composition. */
export function documentToTemplateCode(doc: ArtisanDocument): string {
  const name = ident(doc.name || doc.id);
  const json = serializeDocument(doc).trimEnd().split('\n').join('\n');
  return `// Generated by GameArtisan Studio — ${new Date().toISOString().slice(0, 10)}
import { compositionFromDocument, deserializeDocument, type ArtisanDocument } from '@game-artisan/core';

export const ${name}Document: ArtisanDocument = deserializeDocument(${json});

export const ${name}Composition = compositionFromDocument(${name}Document);
`;
}

/** Props JSON (with `$overrides` when the canvas deviates from the template). */
export function propsToJson(props: Record<string, unknown>, overrides?: LayerOverrides): string {
  const out: Record<string, unknown> = { ...props };
  if (overrides && Object.keys(overrides).length) out.$overrides = overrides;
  return JSON.stringify(out, null, 2);
}

/** A ready-to-paste `<Composition />` registration using the current props as defaultProps. */
export function compositionCode(opts: { id: string; componentName: string; schemaName?: string; width: number; height: number; props: Record<string, unknown>; overrides?: LayerOverrides }): string {
  const props = JSON.stringify(opts.props, null, 2).replace(/\n/g, '\n      ');
  const ov = opts.overrides && Object.keys(opts.overrides).length ? `\n// Canvas overrides — pass as props.$overrides or bake them into the component:\n// ${JSON.stringify(opts.overrides)}\n` : '';
  return `<Composition
  id="${opts.id}"
  width={${opts.width}}
  height={${opts.height}}
  component={${opts.componentName}}${opts.schemaName ? `\n  schema={${opts.schemaName}}` : ''}
  defaultProps={${props}}
/>${ov}`;
}

/** Deep diff of two prop objects → list of changed paths (Studio "deviates from defaults" indicator). */
export function diffProps(a: Record<string, unknown>, b: Record<string, unknown>, prefix = ''): string[] {
  const keys = new Set([...Object.keys(a ?? {}), ...Object.keys(b ?? {})]);
  const out: string[] = [];
  for (const k of keys) {
    const p = prefix ? `${prefix}.${k}` : k;
    const va = (a ?? {})[k];
    const vb = (b ?? {})[k];
    if (va && vb && typeof va === 'object' && typeof vb === 'object' && !Array.isArray(va) && !Array.isArray(vb)) out.push(...diffProps(va as any, vb as any, p));
    else if (JSON.stringify(va) !== JSON.stringify(vb)) out.push(p);
  }
  return out;
}
